import { build } from 'esbuild';
import { writeFile, mkdir, rm } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import { generateSystemPrompt } from '@openuidev/lang-core';

const directory = path.resolve('.work/visual-prompt');
await mkdir(directory, {recursive:true});
const outfile = path.join(directory, 'library.mjs');
await build({entryPoints:['renderer/src/chat/visuals/library.tsx'],outfile,bundle:true,platform:'node',format:'esm',packages:'external',jsx:'automatic'});
try {
  const {library} = await import(pathToFileURL(outfile).href);
  const prompt = generateSystemPrompt({library:library.toSpec(),promptOptions:{
    bindings:true,builtinFunctions:true,toolCalls:false,
    preamble:'The following is the OpenUI 1.0 language specification for an optional visual block within a ScholarLite answer. It applies only inside an openui code fence.',
    additionalRules:[
      'Object keys containing non-ASCII characters must always be double-quoted, for example {"方案": "A", "延迟": 12}. ASCII keys are recommended.',
      'Only use this registered library. Keep diagrams and charts readable in a 300px-wide column.',
      'Numbers must come from supplied material or be explicitly labeled as hypothetical; do not invent measurements.',
      'Use an interactive control only when changing it meaningfully changes the displayed result.',
      'No network, external URL actions, Query, Mutation, or executable HTML is available.',
    ],
  }});
  await mkdir('shared/generated',{recursive:true});
  await writeFile('shared/generated/visual-library-prompt.ts',`// Generated by node scripts/generate-visual-prompt.mjs; do not edit.\nexport const visualLibraryPrompt = ${JSON.stringify(prompt)};\n`);
  console.log(`Generated visual library prompt (${prompt.length} characters, ${Object.keys(library.components).length} components).`);
} finally { await rm(outfile,{force:true}); }
