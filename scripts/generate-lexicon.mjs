import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { getDocument } from 'pdfjs-dist/legacy/build/pdf.mjs';

/**
 * Build a deterministic, front-compressed modern American English lexicon
 * (`shared/generated/english-lexicon.ts`) verified by macOS `NSSpellChecker` (`en_US`).
 *
 * Candidate pool:
 *   1. `/usr/share/dict/words` and `/usr/share/dict/web2a`
 *   2. Unbroken mid-line alphabetic words harvested from local library PDFs (if available)
 * Every candidate must pass `NSSpellChecker` (`en_US`) so archaic 1934 non-words,
 * OCR noise, and concatenated compounds are excluded.
 */
const candidates = new Set();

for (const dictPath of ['/usr/share/dict/words', '/usr/share/dict/web2a']) {
  if (!fsSync.existsSync(dictPath)) continue;
  const raw = await fs.readFile(dictPath, 'utf8');
  for (const line of raw.split('\n')) {
    const w = line.trim().toLowerCase();
    if (w.length >= 2 && w.length <= 22 && /^[a-z]+$/.test(w)) {
      candidates.add(w);
    }
  }
}

const libraryDir = path.join(os.homedir(), 'Library/Application Support/ScholarLite/library');
if (fsSync.existsSync(libraryDir)) {
  const files = (await fs.readdir(libraryDir)).filter(f => f.endsWith('.pdf')).sort().slice(0, 160);
  for (const file of files) {
    try {
      const data = new Uint8Array(await fs.readFile(path.join(libraryDir, file)));
      const pdf = await getDocument({ data, useSystemFonts: true, verbosity: 0 }).promise;
      const maxPage = Math.min(pdf.numPages, 20);
      for (let p = 1; p <= maxPage; p++) {
        const tc = await (await pdf.getPage(p)).getTextContent();
        for (const item of tc.items) {
          if (!item.str) continue;
          const clean = item.hasEOL ? item.str.replace(/[A-Za-z0-9-]+-\s*$/, '') : item.str;
          for (const match of clean.matchAll(/(?<![A-Za-z-])[a-zA-Z]{3,22}(?![A-Za-z-])/g)) {
            candidates.add(match[0].toLowerCase());
          }
        }
      }
      await pdf.destroy();
    } catch {
      /* Skip unreadable PDFs */
    }
  }
}

const tempDir = await fs.mkdtemp(path.join(os.tmpdir(), 'scholarlite-lexicon-'));
try {
  const inputPath = path.join(tempDir, 'candidates.txt');
  const outputPath = path.join(tempDir, 'verified.txt');
  await fs.writeFile(inputPath, [...candidates].sort().join('\n'), 'utf8');

  const swiftScript = `
import Foundation
import AppKit

let args = CommandLine.arguments
let input = try! String(contentsOfFile: args[1], encoding: .utf8)
let checker = NSSpellChecker.shared
var valid = [String]()
for line in input.split(separator: "\\n") {
    let w = String(line)
    let r = checker.checkSpelling(of: w, startingAt: 0, language: "en_US", wrap: false, inSpellDocumentWithTag: 0, wordCount: nil)
    if r.location == NSNotFound {
        valid.append(w)
    }
}
try! valid.sorted().joined(separator: "\\n").write(toFile: args[2], atomically: true, encoding: .utf8)
`;
  execFileSync('swift', ['-e', swiftScript, inputPath, outputPath], { stdio: 'inherit' });

  const verified = (await fs.readFile(outputPath, 'utf8')).split('\n').filter(Boolean);
  const encoded = [];
  let prev = '';
  for (const word of verified) {
    let shared = 0;
    const limit = Math.min(prev.length, word.length, 35);
    while (shared < limit && prev.charCodeAt(shared) === word.charCodeAt(shared)) {
      shared++;
    }
    const prefixCode = shared < 10 ? String(shared) : String.fromCharCode(65 + shared - 10);
    encoded.push(prefixCode + word.slice(shared));
    prev = word;
  }

  await fs.mkdir('shared/generated', { recursive: true });
  const targetFile = 'shared/generated/english-lexicon.ts';
  const payload = encoded.join('\n');
  await fs.writeFile(
    targetFile,
    `// Generated by node scripts/generate-lexicon.mjs; do not edit.\nexport const ENGLISH_LEXICON_DELTA = ${JSON.stringify(payload)};\n`,
    'utf8',
  );
  console.log(`Generated ${targetFile}: ${verified.length} words (${Math.round(payload.length / 1024)} KB).`);
} finally {
  await fs.rm(tempDir, { recursive: true, force: true });
}
